<#
.SYNOPSIS
  WW_set_tee_level - writes the ACTIVE tee profile (WW_tee_events.psd1) for a chosen level.

.DESCRIPTION
  Reads the ONE master file (WW_tee_master.psd1), merges levels 1..N (a level contains
  its own tags plus every lower level's), and writes a flat active profile with a header:
      Level, ProfileVersion (the master's MasterVersion), Generated (UTC), GeneratedBy.
  Level 0 writes an empty (silent) profile.

  Safe by construction: the master is read with Import-PowerShellDataFile (no code runs),
  the result is validated by re-reading it, and the active file is replaced atomically.
  On ANY error the current active profile is left untouched and Success=$false is returned.

  Used by: installer (reapply level on upgrade), the cpr_tee_<N>.flag handler in WW_main,
  the revert timer, and the admin console. Dot-source it to get the functions, or run it:

      .\WW_set_tee_level.ps1 -Level 2
      .\WW_set_tee_level.ps1 -Level 1 -MasterPath .\WW_tee_master.psd1 -ActivePath .\out.psd1

.OUTPUTS
  [pscustomobject] Success, Level, PreviousLevel, Path, Error
#>
[CmdletBinding()]
param(
    [ValidateRange(-1,5)][int]$Level = -1,
    [string]$MasterPath = (Join-Path $PSScriptRoot 'WW_tee_master.psd1'),
    [string]$ActivePath = (Join-Path $PSScriptRoot 'WW_tee_events.psd1'),
    [string]$GeneratedBy = 'WW_set_tee_level'
)

function Read-CprTeeMaster {
    param([Parameter(Mandatory)][string]$MasterPath)
    $data = Import-PowerShellDataFile -LiteralPath $MasterPath -ErrorAction Stop
    if (-not $data.ContainsKey('Levels') -or $null -eq $data.Levels) { throw "master has no Levels section" }
    if ([string]::IsNullOrWhiteSpace([string]$data.MasterVersion)) { throw "master has no MasterVersion" }
    return $data
}

function Get-CprTeeLevelProfile {
    <#
    Returns @{ Events = <merged hashtable>; MasterVersion; Level } for levels 1..Level.
    A tag defined in two levels is a master error and throws (the Pester test also guards it).
    #>
    param(
        [Parameter(Mandatory)][ValidateRange(0,5)][int]$Level,
        [string]$MasterPath = (Join-Path $PSScriptRoot 'WW_tee_master.psd1'),
        $Master
    )
    if ($null -eq $Master) { $Master = Read-CprTeeMaster -MasterPath $MasterPath }
    $events = @{}
    for ($i = 1; $i -le $Level; $i++) {
        $section = $Master.Levels["L$i"]
        if ($null -eq $section -or $null -eq $section.Events) { continue }
        foreach ($tag in $section.Events.Keys) {
            if ($events.ContainsKey($tag)) { throw "tag '$tag' is defined in more than one level" }
            $events[$tag] = $section.Events[$tag]
        }
    }
    return [pscustomobject]@{ Events = $events; MasterVersion = [string]$Master.MasterVersion; Level = $Level }
}

function ConvertTo-CprPsdString {
    param([string]$Value)
    return "'" + ($Value -replace "'", "''") + "'"
}

function ConvertTo-CprTeeProfileText {
    param([Parameter(Mandatory)]$LevelProfile, [string]$GeneratedBy = 'WW_set_tee_level')
    $nl = "`r`n"
    $sb = [System.Text.StringBuilder]::new()
    [void]$sb.Append("@{$nl")
    [void]$sb.Append("    # GENERATED by $GeneratedBy from WW_tee_master.psd1 - do not hand edit.$nl")
    [void]$sb.Append("    # To change the level: cpr_tee_<N>.flag, the admin console, or WW_set_tee_level.ps1 -Level N.$nl")
    [void]$sb.Append("    # To keep a hand-edited profile across upgrades, add:  Custom = `$true$nl")
    [void]$sb.Append("    Level          = $([int]$LevelProfile.Level)$nl")
    [void]$sb.Append("    ProfileVersion = $(ConvertTo-CprPsdString $LevelProfile.MasterVersion)$nl")
    [void]$sb.Append("    Generated      = $(ConvertTo-CprPsdString ([datetime]::UtcNow.ToString('o')))$nl")
    [void]$sb.Append("    GeneratedBy    = $(ConvertTo-CprPsdString $GeneratedBy)$nl")
    [void]$sb.Append("    Events = @{$nl")
    foreach ($tag in ($LevelProfile.Events.Keys | Sort-Object)) {
        $def = $LevelProfile.Events[$tag]
        $fields = @($def.fields | ForEach-Object { ConvertTo-CprPsdString ([string]$_) })
        [void]$sb.Append("        $tag = @{ action = $(ConvertTo-CprPsdString ([string]$def.action)); fields = @($($fields -join ',')) }$nl")
    }
    [void]$sb.Append("    }$nl}$nl")
    return $sb.ToString()
}

function Get-CprActiveTeeLevelInfo {
    <# Reads Level / ProfileVersion / Custom from the active profile. Never throws. #>
    param([string]$ActivePath = (Join-Path $PSScriptRoot 'WW_tee_events.psd1'))
    $info = [pscustomobject]@{ Exists = $false; Level = $null; ProfileVersion = $null; Custom = $false; Readable = $false }
    if (-not (Test-Path -LiteralPath $ActivePath)) { return $info }
    $info.Exists = $true
    try {
        $d = Import-PowerShellDataFile -LiteralPath $ActivePath -ErrorAction Stop
        $info.Readable = $true
        if ($null -ne $d.Level) {
            $n = 0
            if ([int]::TryParse([string]$d.Level, [ref]$n) -and $n -ge 0 -and $n -le 5) { $info.Level = $n }
        }
        $info.ProfileVersion = $d.ProfileVersion
        $info.Custom = ($d.Custom -eq $true)
    } catch { }
    return $info
}

function Set-CprTeeLevel {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][ValidateRange(0,5)][int]$Level,
        [string]$MasterPath = (Join-Path $PSScriptRoot 'WW_tee_master.psd1'),
        [string]$ActivePath = (Join-Path $PSScriptRoot 'WW_tee_events.psd1'),
        [string]$GeneratedBy = 'WW_set_tee_level'
    )
    $result = [pscustomobject]@{ Success = $false; Level = $Level; PreviousLevel = $null; Path = $ActivePath; Error = $null }
    $tmp = "$ActivePath.new"
    try {
        $result.PreviousLevel = (Get-CprActiveTeeLevelInfo -ActivePath $ActivePath).Level
        $lp = Get-CprTeeLevelProfile -Level $Level -MasterPath $MasterPath
        $text = ConvertTo-CprTeeProfileText -LevelProfile $lp -GeneratedBy $GeneratedBy
        Set-Content -LiteralPath $tmp -Value $text -Encoding UTF8 -Force -ErrorAction Stop

        # Validate before it goes live: must parse, carry the right Level, and hold every tag.
        $check = Import-PowerShellDataFile -LiteralPath $tmp -ErrorAction Stop
        if ([int]$check.Level -ne $Level) { throw "validation: Level mismatch" }
        if (@($check.Events.Keys).Count -ne @($lp.Events.Keys).Count) { throw "validation: tag count mismatch" }

        if (Test-Path -LiteralPath $ActivePath) {
            Copy-Item -LiteralPath $ActivePath -Destination "$ActivePath.bak" -Force -ErrorAction SilentlyContinue
        }
        Move-Item -LiteralPath $tmp -Destination $ActivePath -Force -ErrorAction Stop
        $result.Success = $true
    } catch {
        $result.Error = "$($_.Exception.Message)"
        Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue
    }
    return $result
}

# Run directly (not dot-sourced) with -Level: apply and set the exit code.
if ($MyInvocation.InvocationName -ne '.' -and $Level -ge 0) {
    $r = Set-CprTeeLevel -Level $Level -MasterPath $MasterPath -ActivePath $ActivePath -GeneratedBy $GeneratedBy
    if ($r.Success) { Write-Output "tee level $($r.Level) written to $($r.Path) (was: $(if ($null -ne $r.PreviousLevel) { $r.PreviousLevel } else { 'unknown' }))"; exit 0 }
    Write-Error "tee level change failed: $($r.Error)"; exit 1
}
